/**
 * §5-7/5-8 번호 목록 표식 — 「거짓말 3개를 줬는데 몇 번째를 보는지 모르겠다」(PM 피드백) 대응.
 * 여러 항목(거짓말·그날 밤·미션·말투)을 쪽 나눔 없이 한 화면에 ①②③ 로 보여줄 때 쓰는 순수 표시 유틸.
 * 21번째부터는 원문자가 없어 "21." 로 대체한다(실제 데이터는 10개를 넘지 않는다).
 */
const CIRCLED_DIGITS = ['①', '②', '③', '④', '⑤', '⑥', '⑦', '⑧', '⑨', '⑩', '⑪', '⑫', '⑬', '⑭', '⑮', '⑯', '⑰', '⑱', '⑲', '⑳'];

export function circledNum(n: number): string {
  return CIRCLED_DIGITS[n - 1] ?? `${n}.`;
}
